# 基本切分 + 幂等
# ---------------------------------------------------------------------------

def test_basic_cut():
    _check("她推开沉重的门。老师静静站在窗边。",
           ["她推开沉重的门。", "老师静静站在窗边。"], "基本多句")
    _check("走吧！快一点？嗯。", ["走吧！", "快一点？", "嗯。"], "!? 句末")
    _check("一句没有标点的文本", ["一句没有标点的文本"], "无标点单段")
    _check("她推开沉重的门。", ["她推开沉重的门。"], "幂等单句")
    # 连续句末标点吞并
    _check("什么？！不可能！", ["什么？！", "不可能！"], "连续标点吞并")
    # 分号句界（前句较长 → 不被碎句合并吞并; 对齐旧 _split_sentences 行为）
    _check("她犹犹豫豫地停下脚步；远处的钟声敲响了。",
           ["她犹犹豫豫地停下脚步；", "远处的钟声敲响了。"], "分号句界")
    # 省略号不算句末
    _check("她沉默……然后走了。", ["她沉默……然后走了。"], "省略号不切")


def test_whitespace_strip():
    assert split_paragraph("") == []
    assert split_paragraph("   ") == []
    assert split_paragraph(" 你好。 ") == ["你好。"]


