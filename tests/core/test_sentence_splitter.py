def test_merge_short():
    # 连续裸旁白短句 → 并成一段（总长 ≤ MERGE_MAX）
    _check("她点头。她笑了。她转身走了出去。",
           ["她点头。她笑了。她转身走了出去。"], "连续短句合并")
    # 强情绪短句不并
    _check("好！她推开门。", ["好！", "她推开门。"], "强情绪不并")
    # 引号句不参与合并（对白独立）
    _check("「嗯。」她点了点头。",
           ["「嗯。」", "她点了点头。"], "引号块不并")
    # 长句 + 粘连虚词后句 → 合并
    _check("她鼓起勇气。然后，推开了门。",
           ["她鼓起勇气。然后，推开了门。"], "虚词合并")
    # 长句 + 无虚词后句 → 不并
    _check("她站在门口犹豫了很久。老师还在等着她回来。",
           ["她站在门口犹豫了很久。", "老师还在等着她回来。"], "长句不并")


def test_merge_length_cap():
    # 合并结果 ≤ MERGE_MAX 可见字（超出 → 余句独立）
    many = "她点头。" * 20
    got = split_paragraph(many)
    # 每句 3 可见字: 30 字上限 → 前 10 句并成一段, 剩余 10 句再并成一段
    assert got == ["她点头。" * 10, "她点头。" * 10], got
    assert visible_len(got[0]) <= MERGE_MAX
    assert visible_len(got[1]) <= MERGE_MAX


def test_merge_min_boundary():
    # 恰好 MERGE_MIN 字的旁白句仍并入; 超过不并
    short = "她点头。她推开了门。"
    # "她点头。" = 3 可见字（碎）→ 并; "她推开了门。" = 6 可见字?
    _check(short, ["她点头。她推开了门。"], "碎句并长句")
    # 6 字句 + 后续（7 字）→ 6 ≤ MERGE_MIN → 并（阈值含 6）
    _check("她停下脚步。她看了看四周。",
           ["她停下脚步。她看了看四周。"], "阈值边界 6")


def test_merge_no_span_paragraphs():
    """自然段 = 强边界（调用方逐段; 本函数对单段内合并, 跨段不合并由调用保证）。"""
    # 两个独立自然段分别调用 → 各自合并, 互不影响
    a = split_paragraph("她点头。她笑了。")
    b = split_paragraph("她回头。她走了。")
    assert a == ["她点头。她笑了。"]
    assert b == ["她回头。她走了。"]


