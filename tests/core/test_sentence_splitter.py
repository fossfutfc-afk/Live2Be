def test_regression_bracket_fragments():
    """2026-09-02 实测: LLM 曾输出 （动作+内心） 与 ） 拆分 —— 现在输入整段自然文,
    切分器产出完整句段, 不会出现光秃秃的 ） 段。"""
    text = ("（她站在窗边，指尖无意识地拨弄着那一小盆杂草的叶片。"
            "老师……说我是花……是、是真的吗……）那个……老师，今天，我能去找您吗？")
    got = split_paragraph(text)
    assert len(got) == 2, got
    assert got[0].startswith("（") and got[0].endswith("）"), got[0]
    assert got[1].startswith("那个……"), got[1]
    # 没有任何句段是纯括号/纯标点
    assert all(len(g.strip("（）「」…。！？ ")) > 0 for g in got), got


def test_regression_quote_fragments():
    text = "「嗯……那、那我马上过去。老师，请、请等我一下！」她转身跑远。"
    got = split_paragraph(text)
    assert got == ["「嗯……那、那我马上过去。老师，请、请等我一下！」",
                   "她转身跑远。"], got


