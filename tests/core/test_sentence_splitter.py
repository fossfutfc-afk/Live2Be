"""sentence_splitter 切分器单测（2026-09-02: 断句权移交程序的规则全集）。"""
from core.bond.sentence_splitter import (
    MERGE_MAX,
    MERGE_MIN,
    split_paragraph,
    visible_len,
)


def _check(text, expected, tag=""):
    got = split_paragraph(text)
    assert got == expected, f"[{tag}] {text!r}\n  got={got}\n  want={expected}"
    print(f"    ok ({tag}): {text!r} -> {got}")


