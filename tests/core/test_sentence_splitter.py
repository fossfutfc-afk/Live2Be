def test_connective_jieba():
    """jieba 虚词判定（正式依赖）: 后句以粘连虚词开头 → 弱句界; 普通句 → 否。"""
    from core.bond.sentence_splitter import _starts_with_connective
    assert _starts_with_connective("然后，她笑了。") is True
    assert _starts_with_connective("只见她慢慢抬起头。") is True
    assert _starts_with_connective("她轻轻笑了。") is False
    assert _starts_with_connective("「没事的。」") is False
