def test_orphan_symbols():
    _check("（她笑了笑。然后她走了。",
           ["她笑了笑。然后她走了。"], "孤开括号移除")
    _check("她说到一半。）然后她走了。",
           ["她说到一半。然后她走了。"], "孤闭括号移除")
    _check("「她说了一句。", ["她说了一句。"], "孤开引号移除")
    # 半角括号不动（ASCII 语境）
    got = split_paragraph("他说 (maybe). 他转身离开了教室。")
    assert "(" in got[0] and got == ["他说 (maybe).", "他转身离开了教室。"], got


