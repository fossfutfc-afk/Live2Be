def test_quote_block():
    _check("「我来了。您等很久了吗？」她问。",
           ["「我来了。您等很久了吗？」", "她问。"], "引号块内句号不切")
    _check("「嗯。」她点了点头。",
           ["「嗯。」", "她点了点头。"], "引号块独立成句")
    _check("「……老师，我、我来了。」她压低声音，还是有一丝颤。",
           ["「……老师，我、我来了。」", "她压低声音，还是有一丝颤。"],
           "引号块含省略号")


def test_paren_block():
    _check("（她站在门口，还能听到心跳。她深吸一口气。）「打扰了。」",
           ["（她站在门口，还能听到心跳。她深吸一口气。）", "「打扰了。」"],
           "括号块内句号不切")
    _check("她走近。（她犹豫了一下。然后说。）她开口了。",
           ["她走近。", "（她犹豫了一下。然后说。）", "她开口了。"],
           "括号块自成句")
    _check("她开口（声音很小）说完了。",
           ["她开口（声音很小）说完了。"], "括号短语并入句内")
    _check("她开口（声音很小）。说完了。",
           ["她开口（声音很小）。", "说完了。"], "括号后句号归属")


def test_nested_block():
    _check("（她推开门。「打扰了。」她小声说。）",
           ["（她推开门。「打扰了。」她小声说。）"], "括号嵌引号联合保护")


def test_emoticon_and_numbering():
    # :) 不误判为括号对; 文本保留原样
    _check("她发来 :) 表示开心。她仔细看着屏幕。",
           ["她发来 :) 表示开心。", "她仔细看着屏幕。"], "表情不配对")
    _check("第一步：1) 打开盖子。第二步：2) 关闭盖子。",
           ["第一步：1) 打开盖子。", "第二步：2) 关闭盖子。"], "编号括号不配对")
    # 成对括号 + 表情共存; 括号短语不单独断句（并入所在句）
    _check("（笑）:) 好。", ["（笑）:) 好。"], "短语块+表情共存")


