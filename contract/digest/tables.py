def is_full_date(v: str) -> bool:
    """`YYYY-MM-DD`（**全日期**）—— `due` 唯一的格式规矩。

    ⚠️ **公开**: 料那一侧（`material._due_cell` / 资格位）**也要判同一件事** —— "什么算全
    日期"只许有这一个实现, 否则"料里印成日期、契约当没期限"就会漂。

    ⚠️ **只在这里校验格式**: 引擎判"过期没有"时用 `date` 自己比 —— **绝不把它喂给
    `worldtime.age.age_days`**（那个吃的是节点 `ts` 那种 **aware** 时间戳, 裸日期会
    `aware − naive` 当场 TypeError）。
    """
    try:
        date.fromisoformat(v)
    except ValueError:
        return False
    return True
